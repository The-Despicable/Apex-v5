#!/bin/sh
# APEX v5 — master verification harness.
# Runs every mechanical check the public artifacts rely on, and writes evidence/EVIDENCE.md.
# This script is the proof behind the claim markers used in persona and posts.
set -u
ROOT=/home/yaser/apex-v5
cd "$ROOT" || exit 1
T="${TMPDIR:-/tmp}/apex-v5-verify"
rm -rf "$T"; mkdir -p "$T"
: > "$T/all.txt"
section() { printf '\n===== %s =====\n' "$1" | tee -a "$T/all.txt"; }
note() { printf '%s\n' "$1" | tee -a "$T/all.txt"; }
run() {
  label="$1"; shift
  out=$("$@" 2>&1); rc=$?
  printf '%s\n' "$out" >> "$T/all.txt"
  if [ "$rc" -eq 0 ]; then note "RESULT $label: PASS (rc=0)";
  else note "RESULT $label: FAIL (rc=$rc)"; fi
  return "$rc"
}
overall=0
mark() { [ "$1" -eq 0 ] || overall=1; }

section '0. Environment and date'
note "date -u: $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
note "os: $(uname -s)"; note "git: $(git --version 2>/dev/null | head -1)"

section '1. No future-dated or fabricated verification claims'
future=$(grep -RInE '2026-11-1[7-9]|2026-1[2-9]|2027-' persona docs README.md POST-linkedin.md 2>/dev/null || true)
if [ -z "$future" ]; then note 'PASS: no future-dated claims in public artifacts'; mark 0;
else note "FAIL: future-dated claims found:"; note "$future"; mark 1; fi

section '2. Structural lint of persona'
run 'lint.sh' sh verify/lint.sh; mark $?

section '3. Claim ledger resolves every marker'
used=$(grep -rhoE '\[C-[a-z0-9-]+\]' persona/apex.md README.md POST-linkedin.md docs/*.md 2>/dev/null | sort -u | tr -d '[]')
defined=$(grep -ohE '^### C-[a-z0-9-]+' persona/CLAIMS.md 2>/dev/null | awk '{print $2}' | sort -u)
note "markers used: $(printf '%s' "$used" | tr '\n' ' ')"
note "claims defined: $(printf '%s' "$defined" | tr '\n' ' ')"
unresolved=''
for c in $used; do printf '%s\n' "$defined" | grep -qx "$c" || unresolved="$unresolved $c"; done
if [ -z "$unresolved" ]; then note 'PASS: every marker resolves to a claim'; mark 0;
else note "FAIL: unresolved markers:$unresolved"; mark 1; fi
orphan=''
for c in $defined; do printf '%s\n' "$used" | grep -qx "$c" || orphan="$orphan $c"; done
if [ -z "$orphan" ]; then note 'PASS: no orphan claims'; mark 0;
else note "NOTE: claims not referenced by public artifacts:$orphan"; fi

section '4. Grounding keyword scan (descriptive claims need a marker)'
pat='hook-enforced|is proven|are proven|evals prove|is guaranteed|cannot be bypassed|is enforced by|are enforced by'
hits=$(grep -nE "$pat" persona/apex.md README.md POST-linkedin.md docs/*.md 2>/dev/null || true)
bad=''
printf '%s\n' "$hits" | while IFS= read -r l; do
  [ -z "$l" ] && continue
  case "$l" in *'[C-'*) ;; *) printf '%s\n' "$l" ;; esac
done > "$T/ungrounded"
if [ -s "$T/ungrounded" ]; then
  note 'FAIL: unmarked descriptive claims:'; note "$(cat "$T/ungrounded")"; mark 1
else note 'PASS: all matched descriptive claims carry a marker'; mark 0; fi

section '5. CI gate bypass suite (10 cases)'
run 'bypass-suite.sh' sh verify/bypass-suite.sh; mark $?

section '6. Clean-room install smoke'
run 'install-smoke.sh' sh verify/install-smoke.sh; mark $?

section '7. Risk-path regex coverage'
RE=$(cat gate/risk-paths.re)
for p in src/auth/login.ts db/schema.sql models/user.go terraform/main.tf k8s/deploy.yml .github/workflows/ci.yml openapi.yaml package-lock.json src/safe.ts README.md; do
  printf '%s' "$p" | grep -Eq "$RE" && hit=YES || hit=NO
  note "$p -> $hit"
done
for p in src/auth/login.ts db/schema.sql models/user.go terraform/main.tf k8s/deploy.yml .github/workflows/ci.yml openapi.yaml package-lock.json; do
  printf '%s' "$p" | grep -Eq "$RE" || { note "FAIL: risk regex missed $p"; mark 1; }
done
for p in src/safe.ts README.md; do
  printf '%s' "$p" | grep -Eq "$RE" && { note "FAIL: risk regex over-matched $p"; mark 1; }
done
note 'risk-path coverage checks complete'

section '8. Corrected command fixtures'
f=verify/fixtures/corrected-commands.md
grep -Fq 'rg -n "console\.log|print\(" src/' "$f" && note 'PASS: corrected rg form present' || { note 'FAIL: corrected rg form missing'; mark 1; }
grep -Fq 'import asyncio, json, random, sys' "$f" && note 'PASS: corrected json import present' || { note 'FAIL: corrected import missing'; mark 1; }
grep -Fq 'console\.log\|print(' "$f" && { note 'FAIL: broken rg form still present'; mark 1; } || note 'PASS: broken rg form absent'
printf 'console.log("x")\n' > "$T/rgprobe.txt"
rg -n "console\.log|print\(" "$T/rgprobe.txt" >/dev/null 2>&1 && note 'PASS: corrected rg pattern executes (rc=0)' || { note 'FAIL: corrected rg pattern failed'; mark 1; }

section '9. Final tally'
if [ "$overall" -eq 0 ]; then note 'OVERALL: PASS'; else note 'OVERALL: FAIL'; fi
{
  printf '# APEX v5 — verification evidence\n\n'
  printf 'Generated by `sh verify/verify.sh` on %s.\n\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  printf 'This file is machine-generated. Do not edit by hand.\n\n'
  printf '```text\n'
  cat "$T/all.txt"
  printf '\n```\n'
} > evidence/EVIDENCE.md
note 'wrote evidence/EVIDENCE.md'
exit "$overall"
